GOLD_TIME_SECONDS = 180
SILVER_TIME_SECONDS = 240
BRONZE_TIME_SECONDS = 300


def medal_for_time(elapsed_seconds):
    if elapsed_seconds <= GOLD_TIME_SECONDS:
        return "ZŁOTY"
    if elapsed_seconds <= SILVER_TIME_SECONDS:
        return "SREBRNY"
    if elapsed_seconds <= BRONZE_TIME_SECONDS:
        return "BRĄZOWY"
    return "BRAK"


def adjusted_run_time(elapsed_seconds, coins_collected, deaths):
    return max(0, elapsed_seconds - coins_collected * 0.5 + deaths * 5)
